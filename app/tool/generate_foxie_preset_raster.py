#!/usr/bin/env python3
"""Derive the preset's small color map from the canonical Foxie brand PNG.

Run with Pillow installed; --check verifies the tracked distribution asset.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image

APP = Path(__file__).resolve().parents[1]
SOURCE = APP / 'assets/branding/foxie-fox.png'
TARGET = APP / 'lib/src/models/litchcraft_foxie_raster.dart'
PALETTE = (0x000000, 0xff6700, 0xfecb00, 0x4900e1)


def render_source():
    source = Image.open(SOURCE).convert('RGBA')
    side = max(source.size)
    padded = Image.new('RGBA', (side, side))
    padded.alpha_composite(source, ((side-source.width)//2, (side-source.height)//2))
    reduced = padded.resize((64, 64), Image.Resampling.LANCZOS)
    rows = []
    for y in range(64):
        row = ''
        for x in range(64):
            r, g, b, alpha = reduced.getpixel((x, y))
            rgb = tuple((channel * alpha + 127)//255 for channel in (r, g, b))
            # These six authored presets use true black negative space. Keep
            # the brand's strong core/glow; do not change the original PNG.
            peak = max(rgb)
            # Select the brand hue independently of antialias/glow intensity;
            # otherwise dim gold edges get incorrectly classified as orange.
            hue = tuple(channel * 255 / peak for channel in rgb) if peak else rgb
            index = 0 if peak < 72 else min(range(1, 4), key=lambda p: sum(
                (hue[c] - ((PALETTE[p] >> (16-c*8)) & 255))**2 for c in range(3)))
            row += str(index)
        rows.append(row)
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return ('// Generated by tool/generate_foxie_preset_raster.py; do not edit.\n'
            '// Canonical source: assets/branding/foxie-fox.png\n'
            f'// Source SHA-256: {digest}\n'
            '// Verify: python3 tool/generate_foxie_preset_raster.py --check\n'
            'const List<int> litchcraftFoxiePalette = [\n' +
            ''.join(f'  0x{color:06x},\n' for color in PALETTE) + '];\n\n' +
            'const List<String> litchcraftFoxieRaster = [\n' +
            ''.join(f"  '{row}',\n" for row in rows) + '];\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render_source()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit('Foxie preset raster differs from the canonical brand PNG')
        print('Foxie preset raster matches the canonical brand PNG')
    else:
        TARGET.write_text(expected)


if __name__ == '__main__':
    main()
