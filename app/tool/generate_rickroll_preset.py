"""Generate the bounded semantic RGB asset; requires Pillow, not the release app.

Usage: python3 tool/generate_rickroll_preset.py /path/to/rranim.gif
The source GIF is deliberately never copied into the app's release assets.
"""

import base64
import hashlib
from pathlib import Path
import sys
import re
import textwrap
import zlib

from PIL import Image, ImageOps

SOURCE_SHA256 = "9218939cc5f85280d7431fa015054cb2e108b09c347526f03ccfbcb358962d36"


def main():
    source = Path(sys.argv[1])
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("Unexpected source GIF: replacement requires deliberate review")
    image = Image.open(source)
    if image.size != (498, 427) or image.n_frames != 32:
        raise ValueError("Unexpected source geometry or frame count")
    samples = bytearray()
    # Read the production LED-detail geometry owner, not a copied approximation.
    geometry = (Path(__file__).resolve().parents[1] /
                "lib/src/widgets/litchcraft_tools.dart").read_text()
    geometry = geometry.split("Offset litchcraftEmitterPosition(", 1)[1]
    geometry = geometry.split("class LitchcraftTargetIcon", 1)[0]
    centers = re.findall(r"=> const Offset\(([\d.]+), ([\d.]+)\)", geometry)[:4]
    if len(centers) != 4:
        raise ValueError("Cannot resolve production V3 emitter centers")
    # Subject-centered crop removes the distracting left window; fit without
    # stretching and sample 5x5 area at each centroid. Cool background is dimmed
    # consistently (not per-frame auto exposure), preserving subject motion.
    offsets = [(float(x) * 24, float(y) * 24) for x, y in centers]
    for frame in range(image.n_frames):
        image.seek(frame)
        if image.info.get("duration") != 50:
            raise ValueError("Unexpected source timing")
        framed = image.convert("RGB").crop((95, 0, 455, 427))
        fitted = ImageOps.pad(framed, (192, 192),
                              method=Image.Resampling.LANCZOS, color=(0, 0, 0))
        for row in range(8):
            for column in range(8):
                for dx, dy in offsets:
                    x, y = column * 24 + dx, row * 24 + dy
                    rgb = fitted.transform((5, 5), Image.Transform.EXTENT,
                        (x - 2.5, y - 2.5, x + 2.5, y + 2.5),
                        Image.Resampling.BICUBIC).resize(
                            (1, 1), Image.Resampling.BOX).getpixel((0, 0))
                    red, green, blue = rgb
                    cool = max(0, min(1, (blue - red + 8) / 32))
                    attenuation = 1 - 0.55 * cool
                    samples.extend(round(channel * attenuation) for channel in rgb)
    packed = zlib.compress(samples, level=9)
    encoded = base64.b64encode(packed).decode("ascii")
    output = Path(__file__).resolve().parents[1] / "lib/src/models/litchcraft_rickroll_data.dart"
    output.write_text(
        "// Generated by tool/generate_rickroll_preset.py; do not edit.\n"
        f"// Source SHA256: {SOURCE_SHA256}\n"
        f"// 32 frames, 50 ms each, 256 RGB samples/frame; {len(packed)} packed bytes.\n"
        "const String litchcraftRickrollPackedRgb =\n"
        + "\n".join(f"    '{line}'" for line in textwrap.wrap(encoded, 96)) + ";\n")
    print(f"{len(samples)} RGB bytes -> {len(packed)} packed bytes; {output}")


if __name__ == "__main__":
    main()
