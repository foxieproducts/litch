# PlatformIO extra_script (pre)
#
# Generates wrapper translation units for each native test suite so they can be
# linked into a single fast aggregated runner (test_all_native) without keeping
# dozens of wrapper files tracked in git.

from __future__ import annotations

from pathlib import Path

Import("env")  # type: ignore # noqa: F821


def _WriteIfChanged(path: Path, content: str) -> bool:
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def _Generate() -> None:
    project_dir = Path(env.subst("$PROJECT_DIR"))
    test_dir_opt = env.GetProjectOption("test_dir", "test")
    test_dir = (project_dir / test_dir_opt).resolve()
    agg_dir = test_dir / "test_all_native"
    gen_dir = agg_dir / "generated"

    suites: list[str] = []
    companion_sources: dict[str, list[Path]] = {}
    for entry in test_dir.iterdir():
        if not entry.is_dir():
            continue
        name = entry.name
        if not name.startswith("test_"):
            continue
        if name == "test_all_native":
            continue
        # Long-running/manual suites must be opt-in and should not be linked
        # into the fast aggregated runner.
        if name.endswith("_long") or name.endswith("_manual"):
            continue
        # Some legacy suites keep a neutral directory name but are still
        # intentionally exhaustive/stress-oriented and should remain opt-in.
        if (entry / "ALL_NATIVE_OPT_IN").exists():
            continue
        if not (entry / "test_main.cpp").exists():
            continue
        suites.append(name)
        companion_sources[name] = sorted(
            source
            for source in entry.glob("*.cpp")
            if source.name != "test_main.cpp"
        )

    suites.sort()

    gen_dir.mkdir(parents=True, exist_ok=True)

    expected_names: set[str] = {"all_native_registry.hpp"}
    expected_names |= {f"{suite}.cpp" for suite in suites}
    expected_names |= {
        f"{suite}__{source.stem}.cpp"
        for suite in suites
        for source in companion_sources[suite]
    }

    # Remove only stale generated files (keeps incremental builds fast).
    for p in gen_dir.iterdir():
        if not p.is_file():
            continue
        if p.name in expected_names:
            continue
        if p.suffix not in (".cpp", ".hpp"):
            continue
        p.unlink()

    # Wrapper TU per suite.
    any_changed = False
    for suite in suites:
        aggregate_define = (
            "#define LITCH_ALL_NATIVE_AGGREGATE 1\n"
            if "UNITY_BEGIN()" in (test_dir / suite / "test_main.cpp").read_text(
                encoding="utf-8"
            )
            else ""
        )
        wrapper = (
            aggregate_define
            + f"#define main {suite}_main\n"
            + f"#include \"../../{suite}/test_main.cpp\"\n"
            + f"#undef main\n"
            + ("#undef LITCH_ALL_NATIVE_AGGREGATE\n" if aggregate_define else "")
        )
        any_changed |= _WriteIfChanged(gen_dir / f"{suite}.cpp", wrapper)
        for source in companion_sources[suite]:
            companion_wrapper = (
                "#define LITCH_ALL_NATIVE_AGGREGATE 1\n"
                f"#include \"../../{suite}/{source.name}\"\n"
                "#undef LITCH_ALL_NATIVE_AGGREGATE\n"
            )
            any_changed |= _WriteIfChanged(
                gen_dir / f"{suite}__{source.stem}.cpp",
                companion_wrapper,
            )

    # Registry header used by the aggregator main.
    lines: list[str] = []
    lines.append("#pragma once\n")
    lines.append("// Auto-generated by tools/pio/generate_test_all_native.py\n")
    lines.append("// Do not edit manually.\n\n")
    lines.append("#define ALL_NATIVE_TEST_SUITES(X) \\\n")
    for i, suite in enumerate(suites):
        cont = " \\\n" if i != (len(suites) - 1) else "\n"
        lines.append(f"  X({suite}){cont}")
    lines.append("\n")

    any_changed |= _WriteIfChanged(gen_dir / "all_native_registry.hpp", "".join(lines))

    # Keep output quiet unless something actually changed.
    if any_changed:
        print(f"[test_all_native] generated {len(suites)} suite wrappers")


_Generate()
